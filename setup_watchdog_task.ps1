# Registers watchdog.sh as a Windows Scheduled Task that runs every 5
# minutes, independent of any terminal/Git-Bash session staying open --
# this is what makes the watchdog itself durably unattended, since it would
# otherwise share the exact "dies when its launching session ends" problem
# TraderStuff's own processes had before nohup/disown (see start_system.sh).
#
# Idempotent: re-running this replaces any existing "TraderStuffWatchdog"
# task rather than erroring or duplicating it.
#
# Usage (run from an elevated or normal PowerShell -- Task Scheduler doesn't
# require admin for a per-user task that only runs while logged on):
#   powershell -ExecutionPolicy Bypass -File setup_watchdog_task.ps1

$ErrorActionPreference = "Stop"
$taskName = "TraderStuffWatchdog"
$repoRoot = $PSScriptRoot
# Deliberately NOT `(Get-Command bash.exe).Source` -- on a machine with WSL
# installed, that resolves to C:\Windows\system32\bash.exe (WSL's bash),
# which can't run this Windows-path/PowerShell-interop script correctly.
# watchdog.sh needs Git-for-Windows' bash specifically (the same one every
# other *.sh in this repo assumes).
$candidates = @(
    "C:\Program Files\Git\bin\bash.exe",
    "C:\Program Files (x86)\Git\bin\bash.exe"
)
$bashExe = $candidates | Where-Object { Test-Path $_ } | Select-Object -First 1
if (-not $bashExe) {
    throw "Could not find Git-for-Windows' bash.exe (checked: $($candidates -join ', ')). Edit this script to point at your install."
}

Write-Host "Repo root: $repoRoot"
Write-Host "bash.exe:  $bashExe"

# Regenerate watchdog_silent.vbs with this machine's actual bash.exe path
# baked in, rather than hardcoding it separately in two places. Task
# Scheduler runs THIS .vbs (via wscript.exe) instead of bash.exe directly --
# calling bash.exe straight from a scheduled task pops a visible console
# window every run (every 5 minutes here), which is distracting even though
# the task does nothing user-facing. WshShell.Run's hidden-window-style
# argument (0) is the standard, reliable way to get a truly invisible run --
# more dependable than `powershell -WindowStyle Hidden`, which can still
# flash a window briefly under Task Scheduler in some configurations.
$vbsPath = Join-Path $repoRoot "watchdog_silent.vbs"
$vbsContent = @"
' Auto-generated by setup_watchdog_task.ps1 -- edit that script, not this
' file, if the bash.exe path or working directory ever needs to change.
Set WshShell = CreateObject("WScript.Shell")
WshShell.CurrentDirectory = "$repoRoot"
WshShell.Run """$bashExe"" watchdog.sh", 0, True
"@
Set-Content -Path $vbsPath -Value $vbsContent -Encoding ASCII
Write-Host "Wrote: $vbsPath"

$wscriptExe = Join-Path $env:WINDIR "System32\wscript.exe"
$action = New-ScheduledTaskAction -Execute $wscriptExe -Argument "`"$vbsPath`"" -WorkingDirectory $repoRoot
$trigger = New-ScheduledTaskTrigger -Once -At (Get-Date) -RepetitionInterval (New-TimeSpan -Minutes 5) -RepetitionDuration (New-TimeSpan -Days 3650)
$settings = New-ScheduledTaskSettingsSet `
    -AllowStartIfOnBatteries `
    -DontStopIfGoingOnBatteries `
    -StartWhenAvailable `
    -MultipleInstances IgnoreNew `
    -ExecutionTimeLimit (New-TimeSpan -Minutes 10)
$principal = New-ScheduledTaskPrincipal -UserId "$env:USERDOMAIN\$env:USERNAME" -LogonType Interactive -RunLevel Limited

Unregister-ScheduledTask -TaskName $taskName -Confirm:$false -ErrorAction SilentlyContinue

Register-ScheduledTask -TaskName $taskName -Action $action -Trigger $trigger -Settings $settings -Principal $principal `
    -Description "TraderStuff: checks crypto/stock dashboards + Neo4j every 5min, restarts whichever died (see watchdog.sh)." | Out-Null

Write-Host "`nRegistered scheduled task '$taskName' (runs every 5 minutes)."
Write-Host "Logs: $repoRoot\backtrack_logs\watchdog.log"
Write-Host "Check status:  Get-ScheduledTask -TaskName $taskName | Get-ScheduledTaskInfo"
Write-Host "Remove it:     Unregister-ScheduledTask -TaskName $taskName -Confirm:`$false"
